public class Pixeles {
    private int red;
    private int green;
    private int blue;

    public Pixeles(int red, int green, int blue) {
        this.red = red;
        this.green = green;
        this.blue = blue;
    }

    public int getRed() {
        return red;
    }

    public void setRed() {
        this.red = red;
    }

    public int getGreen() {
        return green;
    }
    
    public void setGreen() {
        this.green = green;
    }

    public int getBlue() {
        return blue;
    }

    public void setBlue() {
        this.blue = blue;
    }
}